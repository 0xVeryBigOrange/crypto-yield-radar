export function matchDreams(text: string): DreamEntry[] {
  const found: DreamEntry[] = [];
  for (const entry of DREAMS) {
    if (entry.keys.some((key) => text.includes(key))) found.push(entry);
    if (found.length >= 4) break;
  }
  return found;
}

