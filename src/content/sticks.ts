function gradeOf(n: number): StickGrade {
  if (n <= 5) return "上上";
  if (n <= 18) return "上吉";
  if (n <= 40) return "中吉";
  if (n <= 70) return "中平";
  if (n <= 88) return "中下";
  return "下下";
}

function line(bank: readonly string[], index: number): string {
  return bank[index % bank.length] ?? bank[0] ?? "";
}

export function stickByNumber(n: number): Stick {
  const index = Math.min(100, Math.max(1, Math.floor(n))) - 1;
  const number = index + 1;
  const grade = gradeOf(number);
  const prefix = `${WHERE[index % WHERE.length] ?? "灯下"}${WHEN[Math.floor(index / WHERE.length)] ?? "微风里"}`;
  const poem = [
    `${prefix}，${line(OPEN, index)}`,
    line(TURN, index * 3 + 1),
    line(IMAGE, index * 5 + 2),
    line(CLOSE, index * 7 + 3),
  ] as const;
  const general = line(GENERAL[grade], index);
  const career = `事业这栏只谈节奏：${grade === "下下" || grade === "中下" ? "今天把范围缩小，做完一件能交差的事就收工。" : "可以往前送一寸，别把一寸说成一里。"}同事和消息都不是签，回复可以晚一刻。`;
  const wealth = `财运这栏不报数字。${grade === "上上" || grade === "上吉" ? "手头松一点的感觉如果出现，用来把生活补齐，不用来证明自己眼光好。" : "今天适合看清楚已经有的，而不是去追一个更响的名字。"}账单可以整理，心情不要写进金额。`;
  const love = `感情这栏：${number % 2 === 0 ? "想说的话先写短。短句比较不容易伤人，也比较容易被听完。" : "对方如果也累，就不要用签去压对方。一起安静也算相处。"}合不合适，比吉凶更取决于你今晚想不想被理解。`;
  const health = `健康这栏不是诊断。${grade === "下下" ? "身体如果在抗议，就让抗议优先于任何计划。" : "喝水、走路、按时吃饭，这三件比签诗更接近照顾。"}睡得着，比想得通更值钱。`;
  return {
    n: number,
    grade,
    title: `第${number}签`,
    poem,
    general,
    career,
    wealth,
    love,
    health,
  };
}

export function allSticks(): Stick[] {
  return Array.from({ length: 100 }, (_item, index) => stickByNumber(index + 1));
}
