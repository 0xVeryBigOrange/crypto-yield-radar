export const TAROT_DECK: readonly TarotCard[] = [
  ...MAJORS.map(([name, upright, reversed], index) => ({
    id: `major-${String(index).padStart(2, "0")}`,
    arcana: "major" as const,
    name,
    upright,
    reversed,
  })),
  ...SUITS.flatMap((suit) =>
    RANKS.map((rank, index) => ({
      id: `${suit.id}-${String(index + 1).padStart(2, "0")}`,
      arcana: "minor" as const,
      name: `${suit.name}${rank}`,
      upright: `${suit.voice}：${suit.up[index] ?? ""}`,
      reversed: `${suit.voice}走反：${suit.down[index] ?? ""}`,
    })),
  ),
];

