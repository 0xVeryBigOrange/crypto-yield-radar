export type SpreadId = keyof typeof SPREADS;

export function spreadOf(value: string): (typeof SPREADS)[SpreadId] & { id: SpreadId } | null {
  if (value in SPREADS) {
    const id = value as SpreadId;
    return { id, ...SPREADS[id] };
  }
  return null;
}
